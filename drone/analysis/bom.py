"""Cost roll-up of the bill of materials against the project budget.

Reads bom.csv next to this file and prints a Markdown report:

    python3 drone/analysis/bom.py > drone/analysis/bom-report.md

Prices are approximate: `listing` means a shop price seen in October 2026, `estimate` means
a typical price for the part. Update `unit_eur` as you buy, and re-run.
"""

import csv
import sys
from pathlib import Path

BUDGET_EUR = 1000
BUDGET_CEILING_EUR = 1500        # the budget plus the agreed "if needed" extra

PRIORITIES = [
    ("now", "Buy now: everything for Blocks 0-2"),
    ("recommended", "Recommended: spares, firmware dev kit, test gear"),
    ("later", "Later: Blocks 3-5 sensors and companion"),
]


def load(path):
    with open(path, newline="") as f:
        rows = list(csv.DictReader(f))
    known = {key for key, _ in PRIORITIES}
    for row in rows:
        if row["priority"] not in known:
            raise ValueError(f"unknown priority {row['priority']!r} for {row['item']!r}")
        row["qty"] = int(row["qty"])
        row["unit_eur"] = float(row["unit_eur"])
        row["total_eur"] = row["qty"] * row["unit_eur"]
    return rows


def report(rows):
    out = []
    p = out.append
    p("# Bill of materials: cost report")
    p("")
    p("_Generated by `bom.py` from `bom.csv`; do not edit by hand._")
    p("")
    p(f"Budget {BUDGET_EUR} EUR, ceiling {BUDGET_CEILING_EUR} EUR. Prices are approximate "
      "(October 2026); `listing` = a shop price we found, `estimate` = typical price.")
    p("")
    p("## Running total")
    p("")
    p("| Stage | Stage cost (EUR) | Running total (EUR) | Within budget | Within ceiling |")
    p("|---|---:|---:|:-:|:-:|")
    running = 0
    for key, label in PRIORITIES:
        stage = sum(r["total_eur"] for r in rows if r["priority"] == key)
        running += stage
        p(f"| {label} | {stage:.0f} | {running:.0f} | "
          f"{'yes' if running <= BUDGET_EUR else 'no'} | "
          f"{'yes' if running <= BUDGET_CEILING_EUR else '**NO**'} |")
    p("")
    estimated = sum(r["total_eur"] for r in rows if r["price_basis"] == "estimate")
    p(f"{estimated / running:.0%} of the total is estimated rather than a seen price, "
      "so leave some slack.")
    p("")

    for key, label in PRIORITIES:
        p(f"## {label}")
        p("")
        p("| Category | Item | Qty | Unit (EUR) | Total (EUR) | Price | Where | Notes |")
        p("|---|---|---:|---:|---:|---|---|---|")
        for r in rows:
            if r["priority"] != key:
                continue
            p(f"| {r['category']} | {r['item']} | {r['qty']} | {r['unit_eur']:.0f} | "
              f"{r['total_eur']:.0f} | {r['price_basis']} | {r['where']} | {r['notes']} |")
        p("")
    return "\n".join(out)


def main():
    rows = load(Path(__file__).with_name("bom.csv"))
    print(report(rows))
    return 0


if __name__ == "__main__":
    sys.exit(main())
